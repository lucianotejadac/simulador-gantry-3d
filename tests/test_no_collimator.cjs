const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const {fixture,project}=require('./bone_performance_fixture.cjs');
const context={window:{},Math,Float32Array,Float64Array,Int32Array};
vm.runInNewContext(fs.readFileSync('scripts/icrp_live.js','utf8'),context);
const field=context.window.GANTRY_ICRP.field;
const points=new Uint16Array(80*120);points[60*80+40]=1000;
const pose={width:80,height:120,pixelMm:10,scale:1,window:1000,frames:[points]};
const pair={lo:0,hi:0,mix:0},crop={x:12,y:32,w:56,h:56};
const m={uncollimated:true,detectorDistanceCm:15,countFactor:30,contrast:1,haloAlpha:0};
const sample=(n=128,c=crop,metrics=m,x=false,y=false)=>field(pose,pair,c,n,n,x,y,metrics,0);
const low=sample(),high=sample(256);
assert(Math.abs(low.sum/high.sum-1)<.001,'matrix size must preserve total counts');
assert(low.values.filter(v=>v>Math.max(...low.values)/2).length>low.values.length*.3,'point source must form broad fluence');
assert(sample(128,crop,{...m,detectorDistanceCm:60}).sum<low.sum,'solid angle falls with distance');
const outside={x:85,y:32,w:56,h:56};
assert(sample(128,outside).sum>0,'sources outside the nominal crop contribute without collimation');
assert.equal(sample(128,outside,{...m,uncollimated:false}).sum,0);
const half=sample(128,crop,{...m,countFactor:15});assert(Math.abs(half.sum/low.sum-.5)<1e-6);
const flipped=sample(128,crop,m,true,true);
for(let i=0;i<low.values.length;i++)assert.equal(low.values[i],flipped.values[low.values.length-1-i]);
const empty={...pose,frames:[new Uint16Array(points.length)]};
assert.equal(field(empty,pair,crop,128,128,false,false,m,0).sum,0,'no source creates no counts');
assert.equal(points[60*80+40],1000,'source atlas is immutable');
(async()=>{
  const W=await fixture(),cache={};
  const start=performance.now(),bare=project(W,{col:'NONE',cache}),elapsed=performance.now()-start;
  const normal=project(W,{col:'LEHR'});
  assert(bare.sum>normal.sum,'unshielded detector sensitivity exceeds collimated sensitivity in this teaching model');
  assert(project(W,{col:'NONE',energy:450}).sum<bare.sum,'energy window still selects detected photons');
  assert.equal(project(W,{col:'NONE',cache}),bare,'unchanged settings reuse the field');
  assert(W.metrics(15,'bone','NONE',140,20).uncollimated);
  console.log('PASS: broad fluence, out-of-field sources, distance, matrix conservation, orientation, energy, sensitivity and caching. MDP 256 build: '+elapsed.toFixed(1)+' ms; rate ratio '+(bare.sum/normal.sum).toFixed(1));
})().catch(e=>{console.error(e);process.exitCode=1;});
