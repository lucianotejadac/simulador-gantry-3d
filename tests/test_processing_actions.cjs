const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({window:{}});
vm.runInContext(fs.readFileSync('scripts/processing_acquisition_actions.js','utf8'),context);
const model=context.window.GANTRY_ACQUISITION_ACTIONS.model;
const enabled=m=>Array.from(m.actions.filter(a=>a.enabled),a=>a.id);
const idle={hasDraft:false,lastId:null,waiting:false,kind:'static'};
assert.deepEqual(enabled(model(idle)),['static','whole','dynamic']);
const draft={...idle,hasDraft:true,kind:'whole'};
assert.equal(model(draft).type,'Cuerpo entero');
assert.deepEqual(enabled(model(draft)),['static','whole','dynamic','start','instant','delete']);
const acquiring={...draft,draftId:'a',lastId:'a',state:{finished:false,speed:60}};
assert.deepEqual(enabled(model(acquiring)),['instant','pause','fast','stop']);
assert.equal(model(acquiring).actions.find(a=>a.id==='fast').label,'Avance rápido · 60×');
const paused=model({...acquiring,state:{paused:true,finished:false}});
assert.equal(paused.phase,'En pausa');
assert.equal(paused.actions.find(a=>a.id==='pause').label,'Reanudar adquisición');
const done={...idle,lastId:'a',state:{finished:true},kind:'whole',selectedId:'older'};
assert.deepEqual(enabled(model(done)),['static','whole','dynamic','add','current','retake','delete']);
assert(!enabled(model({...acquiring,draftId:null})).includes('delete'),'Cannot delete while acquisition runs');
assert(!enabled(model({...acquiring,draftId:null})).includes('start'),'Cannot start a pending tile while another acquisition runs');
assert(!enabled(model({...done,hasDraft:true})).includes('add'));
assert(!enabled(model({...done,selectedId:null})).includes('add'));
assert(!enabled(model({...done,hasDraft:true})).includes('retake'),'New draft must not overwrite the previous acquisition');
assert(!enabled(model({...done,selectedId:null})).includes('retake'));
assert.deepEqual(enabled(model({...acquiring,waiting:true})),[]);
const ids=Array.from(model(idle).actions,a=>a.id);
assert.deepEqual(Array.from(model(acquiring).actions,a=>a.id),ids,'Menu action order is stable');
assert.equal(new Set(ids).size,ids.length,'No duplicate actions');
console.log('OK: shared menu/transport actions across empty, draft, running, paused, completed, cancelled and pending states.');
